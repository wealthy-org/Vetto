#!/usr/bin/env python3
"""Regenerate the inlined wallet marks used by the sign-in picker.

The picker ships official brand icons as data URIs (see
apps/web/components/wallet-logos.ts) so no third-party request happens at
runtime. This script is the only supported way to rebuild them: it downloads
each mark from the wallet vendor's own site/CDN, downsizes it to 96px and
re-emits the TypeScript module.

    python3 scripts/wallet-logos.py

Requires: pillow (pip install pillow) and network access.

Trademarks belong to their owners. These marks are used only to identify the
wallet a visitor is connecting.
"""

from __future__ import annotations

import base64
import io
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "apps" / "web" / "components" / "wallet-logos.ts"
SIZE = 96

# id -> (source URL, kind)
SOURCES: dict[str, tuple[str, str]] = {
    "phantom": ("https://phantom.app/_web_platform_assets/apple-touch-icon.png", "png"),
    "metamask": ("https://metamask.io/favicons/default/favicon.svg", "svg"),
    "rabby": (
        "https://raw.githubusercontent.com/RabbyHub/Rabby/develop/_raw/images/icon-128.png",
        "png",
    ),
    "coinbase": ("https://wallet.coinbase.com/static-open-graph/v1/favicon.png", "png"),
    "walletconnect": ("https://walletconnect.com/icon.png", "png"),
}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "vetto-wallet-logos/1"})
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read()


def png_data_uri(raw: bytes) -> str:
    from PIL import Image  # imported lazily so `--help` works without pillow

    image = Image.open(io.BytesIO(raw)).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    out = io.BytesIO()
    image.quantize(colors=64, method=Image.FASTOCTREE).save(out, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(out.getvalue()).decode()


def main() -> None:
    entries: list[str] = []
    for wallet_id, (url, kind) in SOURCES.items():
        raw = fetch(url)
        uri = (
            "data:image/svg+xml," + urllib.parse.quote(raw.decode("utf-8"), safe="")
            if kind == "svg"
            else png_data_uri(raw)
        )
        entries.append(f'  {wallet_id}:\n    "{uri}",')
        print(f"{wallet_id:14} {len(uri):>7} bytes  <- {url}")

    header = [
        'import type { WalletId } from "@/lib/injected-wallet";',
        "",
        "/**",
        " * Official wallet marks, inlined as data URIs so the picker renders the real brand",
        " * icons with no third-party request at runtime (and inside sandboxed previews).",
        " *",
        " * Generated by `scripts/wallet-logos.py` — do not hand-edit. Sources:",
        *[f" *   {wid:<14} {url}" for wid, (url, _) in SOURCES.items()],
        " *",
        " * Trademarks belong to their owners; these are used only to identify the wallet a",
        " * visitor is connecting.",
        " */",
        "export const WALLET_LOGO: Record<WalletId, string> = {",
    ]
    TARGET.write_text("\n".join(header + entries + ["};", ""]), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")


if __name__ == "__main__":
    main()
